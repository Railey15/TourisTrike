import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '../../build/sql-validation/node_modules/@electric-sql/pglite/dist/index.js';

const db = new PGlite();
const migration = await readFile(
  new URL(
    '../migrations/20261010150000_initial_driver_municipality_assignment.sql',
    import.meta.url,
  ),
  'utf8',
);
const uuid = (n) =>
  `30000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const newDriver = uuid(1);
const existingDriver = uuid(2);
const pulilanOffice = uuid(3);
const baliwagOffice = uuid(4);
const tourist = uuid(5);
let checks = 0;

async function check(name, action) {
  try {
    await action();
    checks++;
  } catch (error) {
    error.message = `${name}: ${error.message}`;
    throw error;
  }
}

async function asUser(userId, sql, params = [], persist = false) {
  await db.exec('begin');
  try {
    await db.query("select set_config('request.jwt.claim.sub',$1,true)", [
      userId,
    ]);
    await db.query(
      "select set_config('request.jwt.claim.role','authenticated',true)",
    );
    await db.exec('set local role authenticated');
    const result = await db.query(sql, params);
    await db.exec(persist ? 'commit' : 'rollback');
    return result;
  } catch (error) {
    await db.exec('rollback');
    throw error;
  }
}

try {
  await db.exec(`
    create role authenticated;
    create role anon;
    create schema auth;
    create function auth.uid() returns uuid language sql stable as $$
      select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
    $$;
    create function auth.role() returns text language sql stable as $$
      select nullif(current_setting('request.jwt.claim.role', true), '')
    $$;

    create table public.profiles(
      id uuid primary key,
      role text not null,
      city text,
      province text default 'Bulacan'
    );
    create table public.driver_applications(
      id bigint generated by default as identity primary key,
      driver_id uuid not null references public.profiles(id) on delete cascade,
      city text not null,
      status text not null default 'pending',
      submitted_at timestamptz not null default now(),
      reviewed_by uuid,
      reviewed_at timestamptz,
      rejection_reason text
    );

    create function public.current_profile_role()
    returns text language sql stable security definer set search_path = public as $$
      select role from public.profiles where id = auth.uid()
    $$;
    create function public.current_profile_city()
    returns text language sql stable security definer set search_path = public as $$
      select city from public.profiles where id = auth.uid()
    $$;

    create function public.protect_own_profile_scope()
    returns trigger language plpgsql set search_path = public as $$
    begin
      if auth.uid() = old.id and coalesce(auth.role(), '') <> 'service_role' then
        if new.role is distinct from old.role
          or new.city is distinct from old.city
          or new.province is distinct from old.province then
          raise exception 'ROLE_AND_TENANT_SCOPE_ARE_READ_ONLY';
        end if;
      end if;
      return new;
    end;
    $$;
    create trigger protect_own_profile_scope
      before update on public.profiles
      for each row execute function public.protect_own_profile_scope();

    alter table public.profiles enable row level security;
    alter table public.driver_applications enable row level security;
    create policy profiles_select on public.profiles for select to authenticated
      using (
        id = auth.uid()
        or public.current_profile_role() = 'admin'
        or (
          public.current_profile_role() = 'subtenant'
          and lower(city) = lower(public.current_profile_city())
        )
      );
    create policy profiles_update_self on public.profiles for update to authenticated
      using (id = auth.uid()) with check (id = auth.uid());
    create policy driver_applications_select on public.driver_applications
      for select to authenticated using (
        driver_id = auth.uid()
        or public.current_profile_role() = 'admin'
        or (
          public.current_profile_role() = 'subtenant'
          and lower(city) = lower(public.current_profile_city())
        )
      );
    grant usage on schema public, auth to authenticated;
    grant select, update on public.profiles to authenticated;
    grant select on public.driver_applications to authenticated;

    insert into public.profiles(id,role,city,province) values
      ('${newDriver}','driver',null,'Bulacan'),
      ('${existingDriver}','driver','Baliwag','Bulacan'),
      ('${pulilanOffice}','subtenant','Pulilan','Bulacan'),
      ('${baliwagOffice}','subtenant','Baliwag','Bulacan'),
      ('${tourist}','tourist',null,'Bulacan');
  `);

  await db.exec(migration);

  await check('new Driver can select Pulilan once', async () => {
    const result = await asUser(
      newDriver,
      'select public.assign_initial_driver_municipality($1) as result',
      ['Pulilan'],
      true,
    );
    assert.deepEqual(result.rows[0].result, {
      success: true,
      municipality: 'Pulilan',
      province: 'Bulacan',
      already_assigned: false,
    });
  });

  await check('profile stores authoritative municipality without changing role', async () => {
    const row = (
      await db.query(
        'select role,city,municipality,province from profiles where id=$1',
        [newDriver],
      )
    ).rows[0];
    assert.deepEqual(row, {
      role: 'driver',
      city: 'Pulilan',
      municipality: 'Pulilan',
      province: 'Bulacan',
    });
  });

  await check('assignment creates a pending Pulilan driver application', async () => {
    const row = (
      await db.query(
        'select city,status from driver_applications where driver_id=$1',
        [newDriver],
      )
    ).rows[0];
    assert.deepEqual(row, { city: 'Pulilan', status: 'pending' });
  });

  await check('same assignment is safely idempotent', async () => {
    const result = await asUser(
      newDriver,
      'select public.assign_initial_driver_municipality($1) as result',
      ['pulilan'],
    );
    assert.equal(result.rows[0].result.already_assigned, true);
  });

  await check('Driver cannot change Pulilan after assignment', async () => {
    await assert.rejects(
      () =>
        asUser(
          newDriver,
          'select public.assign_initial_driver_municipality($1)',
          ['Baliwag'],
        ),
      /DRIVER_MUNICIPALITY_ALREADY_ASSIGNED/,
    );
  });

  await check('direct protected-scope update remains blocked', async () => {
    await assert.rejects(
      () =>
        asUser(
          newDriver,
          "update profiles set city='Baliwag',municipality='Baliwag' where id=$1",
          [newDriver],
        ),
      /ROLE_AND_TENANT_SCOPE_ARE_READ_ONLY/,
    );
    await assert.rejects(
      () =>
        asUser(
          newDriver,
          "update profiles set role='tourist' where id=$1",
          [newDriver],
        ),
      /ROLE_AND_TENANT_SCOPE_ARE_READ_ONLY/,
    );
  });

  await check('Pulilan Subtenant sees only the Pulilan Driver', async () => {
    const profiles = await asUser(
      pulilanOffice,
      "select id::text as id from profiles where role='driver' order by id",
    );
    assert.deepEqual(profiles.rows, [{ id: newDriver }]);
    const applications = await asUser(
      pulilanOffice,
      'select driver_id::text as driver_id,city,status from driver_applications',
    );
    assert.deepEqual(applications.rows, [
      { driver_id: newDriver, city: 'Pulilan', status: 'pending' },
    ]);
  });

  await check('other municipality cannot see the Pulilan Driver', async () => {
    const profiles = await asUser(
      baliwagOffice,
      "select id::text as id from profiles where role='driver' order by id",
    );
    assert.deepEqual(profiles.rows, [{ id: existingDriver }]);
    const applications = await asUser(
      baliwagOffice,
      'select driver_id::text as driver_id from driver_applications',
    );
    assert.deepEqual(applications.rows, []);
  });

  await check('existing Driver keeps the assigned municipality', async () => {
    const row = (
      await db.query(
        'select city,municipality,province from profiles where id=$1',
        [existingDriver],
      )
    ).rows[0];
    assert.deepEqual(row, {
      city: 'Baliwag',
      municipality: 'Baliwag',
      province: 'Bulacan',
    });
    await assert.rejects(
      () =>
        asUser(
          existingDriver,
          'select public.assign_initial_driver_municipality($1)',
          ['Pulilan'],
        ),
      /DRIVER_MUNICIPALITY_ALREADY_ASSIGNED/,
    );
  });

  await check('non-Driver and unsupported municipality are rejected', async () => {
    await assert.rejects(
      () =>
        asUser(
          tourist,
          'select public.assign_initial_driver_municipality($1)',
          ['Pulilan'],
        ),
      /Only Driver accounts/,
    );
    await assert.rejects(
      () =>
        asUser(
          newDriver,
          'select public.assign_initial_driver_municipality($1)',
          ['Quezon City'],
        ),
      /UNSUPPORTED_BULACAN_MUNICIPALITY/,
    );
  });

  console.log(
    `PASS: ${checks} initial Driver municipality assignment regression checks`,
  );
} finally {
  await db.close();
}
