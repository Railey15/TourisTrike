import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '../../build/sql-validation/node_modules/@electric-sql/pglite/dist/index.js';

const db = new PGlite();
const migration = await readFile(
  new URL(
    '../migrations/20261010130000_city_admin_application_privacy_fix.sql',
    import.meta.url,
  ),
  'utf8',
);
const forwardMigration = await readFile(
  new URL(
    '../migrations/20261010140000_fix_city_admin_verification_status.sql',
    import.meta.url,
  ),
  'utf8',
);
const uuid = (n) =>
  `20000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const applicant = uuid(1);
const tourist = uuid(2);
const mainTenant = uuid(3);
const driver = uuid(5);
const legacyApplicant = uuid(6);
let checks = 0;

async function check(name, action) {
  try {
    await action();
    checks++;
  } catch (error) {
    error.message = `${name}: ${error.message}`;
    throw error;
  }
}

async function asUser(userId, sql, params = [], persist = false) {
  await db.exec('begin');
  try {
    await db.query("select set_config('request.jwt.claim.sub',$1,true)", [
      userId ?? '',
    ]);
    await db.exec('set local role authenticated');
    const result = await db.query(sql, params);
    await db.exec(persist ? 'commit' : 'rollback');
    return result;
  } catch (error) {
    await db.exec('rollback');
    throw error;
  }
}

const submitSql = `select public.submit_city_admin_application(
  $1,$2,$3,$4,$5,$6,$7,$8
) as result`;
const submitParams = (email = 'office@example.test') => [
  'Malolos',
  'Malolos Tourism Office',
  'Maria Santos',
  '09171234567',
  email,
  'City Hall, Malolos',
  'Maria',
  'Santos',
];

try {
  await db.exec(`
    create role authenticated;
    create role anon;
    create schema auth;
    create table auth.users(id uuid primary key, email text not null);
    create function auth.uid() returns uuid language sql stable as $$
      select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
    $$;
    create table public.profiles(
      id uuid primary key references auth.users(id) on delete cascade,
      role text not null,
      first_name text,
      last_name text,
      full_name text,
      mobile text,
      address text,
      city text,
      province text,
      privacy_notice_version text,
      privacy_notice_acknowledged_at timestamptz
    );
    create table public.city_tenant_registrations(
      id bigint generated by default as identity primary key,
      user_id uuid references public.profiles(id) on delete cascade,
      city text not null,
      office_name text,
      contact_person text,
      contact_number text,
      email text,
      office_address text,
      status text not null default 'pending',
      submitted_at timestamptz not null default now(),
      reviewed_by uuid references public.profiles(id) on delete set null,
      reviewed_at timestamptz,
      rejection_reason text
    );
    create table public.subtenant_details(
      id uuid primary key references public.profiles(id) on delete cascade,
      office_name text,
      city text not null,
      province text not null,
      contact_person text,
      contact_number text,
      email text,
      office_address text,
      verification_status text not null default 'pending'
        constraint subtenant_details_verification_status_check
        check (verification_status in ('pending', 'verified', 'rejected')),
      is_active boolean not null default false,
      approved_by uuid references public.profiles(id),
      approved_at timestamptz,
      updated_at timestamptz not null default now()
    );
    create function public.is_provincial_admin()
    returns boolean language sql stable security definer set search_path = '' as $$
      select exists (
        select 1 from public.profiles
        where id = auth.uid() and role = 'main_tenant'
      )
    $$;
    create function public.stamp_tourist_privacy_notice()
    returns trigger language plpgsql set search_path = '' as $$
    begin
      if new.role = 'tourist' and auth.uid() = new.id then
        if tg_op = 'INSERT' then
          if new.privacy_notice_version is null or
             new.privacy_notice_version not in ('1.0', '1.1') then
            raise exception 'PRIVACY_NOTICE_REQUIRED';
          end if;
          new.privacy_notice_acknowledged_at := now();
        elsif new.privacy_notice_version is distinct from old.privacy_notice_version
           or new.privacy_notice_acknowledged_at is distinct from old.privacy_notice_acknowledged_at then
          raise exception 'PRIVACY_ACKNOWLEDGMENT_IMMUTABLE';
        end if;
      end if;
      return new;
    end;
    $$;
    create trigger stamp_tourist_privacy_notice
      before insert or update on public.profiles
      for each row execute function public.stamp_tourist_privacy_notice();
    grant usage on schema public, auth to authenticated;
    grant select, insert on public.city_tenant_registrations to authenticated;
    grant select on public.profiles to authenticated;
  `);

  await db.query(
    'insert into auth.users(id,email) values($1,$2),($3,$4),($5,$6)',
    [
      applicant,
      'office@example.test',
      tourist,
      'tourist@example.test',
      mainTenant,
      'admin@example.test',
    ],
  );
  await db.query('insert into auth.users(id,email) values($1,$2)', [
    driver,
    'driver@example.test',
  ]);
  await db.query('insert into auth.users(id,email) values($1,$2)', [
    legacyApplicant,
    'legacy-office@example.test',
  ]);
  await db.query(
    "insert into profiles(id,role,province) values($1,'main_tenant','Bulacan')",
    [mainTenant],
  );
  await db.query(
    "insert into profiles(id,role,province) values($1,'driver','Bulacan')",
    [driver],
  );

  // Reproduce the definitions already recorded on the live database, then
  // prove that the forward migration replaces them without rewriting history.
  const deployedMigration = migration.replaceAll("'verified'", "'approved'");
  await db.exec(deployedMigration);
  await db.exec(forwardMigration);

  await check('registration now references auth.users directly', async () => {
    const result = await db.query(`
      select ccu.table_schema, ccu.table_name
      from information_schema.table_constraints tc
      join information_schema.constraint_column_usage ccu
        on ccu.constraint_name = tc.constraint_name
       and ccu.constraint_schema = tc.constraint_schema
      where tc.constraint_name = 'city_tenant_registrations_user_id_fkey'
    `);
    assert.deepEqual(result.rows[0], {
      table_schema: 'auth',
      table_name: 'users',
    });
  });

  await check('fresh applicant submits without a profile', async () => {
    const result = await asUser(applicant, submitSql, submitParams(), true);
    assert.equal(result.rows[0].result.status, 'pending');
    assert.equal(
      (await db.query('select count(*)::integer as count from profiles where id=$1', [applicant])).rows[0].count,
      0,
    );
    const registration = (
      await db.query(
        'select status,city,email from city_tenant_registrations where user_id=$1',
        [applicant],
      )
    ).rows[0];
    assert.deepEqual(registration, {
      status: 'pending',
      city: 'Malolos',
      email: 'office@example.test',
    });
  });

  await check('duplicate pending submission is idempotent', async () => {
    const result = await asUser(applicant, submitSql, submitParams());
    assert.equal(result.rows[0].result.status, 'pending');
    assert.equal(
      (
        await db.query(
          'select count(*)::integer as count from city_tenant_registrations where user_id=$1',
          [applicant],
        )
      ).rows[0].count,
      1,
    );
  });

  await check('authenticated email must match application email', async () => {
    await assert.rejects(
      () => asUser(applicant, submitSql, submitParams('other@example.test')),
      /Official email must match the authenticated account/,
    );
  });

  await check('existing tourist cannot submit as a city admin', async () => {
    await db.query(
      "select set_config('request.jwt.claim.sub',$1,false)",
      [tourist],
    );
    await db.query(
      "insert into profiles(id,role,privacy_notice_version) values($1,'tourist','1.1')",
      [tourist],
    );
    await assert.rejects(
      () =>
        asUser(
          tourist,
          submitSql,
          submitParams('tourist@example.test'),
        ),
      /already belongs to a tourist account/,
    );
  });

  await check('existing tourist cannot be promoted by approval', async () => {
    const registration = (
      await db.query(
        `insert into city_tenant_registrations(
          user_id,city,office_name,contact_person,contact_number,email,
          office_address,status
        ) values($1,'Malolos','Tourist Conflict Office','Tourist User',
          '09170000000','tourist@example.test','City Hall','pending')
        returning id::text as id`,
        [tourist],
      )
    ).rows[0];
    await assert.rejects(
      () =>
        asUser(
          mainTenant,
          'select public.approve_city_registration($1,$2,$3)',
          [registration.id, 'approved', ''],
        ),
      /already has a tourist profile/,
    );
    assert.equal(
      (await db.query('select role from profiles where id=$1', [tourist]))
        .rows[0].role,
      'tourist',
    );
  });

  await check('existing driver cannot be promoted by approval', async () => {
    const registration = (
      await db.query(
        `insert into city_tenant_registrations(
          user_id,city,office_name,contact_person,contact_number,email,
          office_address,status
        ) values($1,'Malolos','Driver Conflict Office','Driver User',
          '09170000001','driver@example.test','City Hall','pending')
        returning id::text as id`,
        [driver],
      )
    ).rows[0];
    await assert.rejects(
      () =>
        asUser(
          mainTenant,
          'select public.approve_city_registration($1,$2,$3)',
          [registration.id, 'approved', ''],
        ),
      /already has a driver profile/,
    );
    assert.equal(
      (await db.query('select role from profiles where id=$1', [driver]))
        .rows[0].role,
      'driver',
    );
  });

  await check('Main Tenant approval creates only a subtenant profile', async () => {
    const registration = (
      await db.query(
        'select id::text as id from city_tenant_registrations where user_id=$1',
        [applicant],
      )
    ).rows[0];
    const result = await asUser(
      mainTenant,
      'select public.approve_city_registration($1,$2,$3) as result',
      [registration.id, 'approved', ''],
      true,
    );
    assert.equal(result.rows[0].result.status, 'approved');
    assert.equal(
      (
        await db.query(
          'select status from city_tenant_registrations where id=$1',
          [registration.id],
        )
      ).rows[0].status,
      'approved',
    );
    const profile = (
      await db.query(
        'select role,city,province,privacy_notice_version from profiles where id=$1',
        [applicant],
      )
    ).rows[0];
    assert.deepEqual(profile, {
      role: 'subtenant',
      city: 'Malolos',
      province: 'Bulacan',
      privacy_notice_version: null,
    });
    const details = (
      await db.query(
        'select city,province,is_active,verification_status from subtenant_details where id=$1',
        [applicant],
      )
    ).rows[0];
    assert.deepEqual(details, {
      city: 'Malolos',
      province: 'Bulacan',
      is_active: true,
      verification_status: 'verified',
    });
  });

  await check('approved applicant cannot gain tourist privacy state', async () => {
    await assert.rejects(
      () =>
        asUser(
          applicant,
          "update profiles set privacy_notice_version='1.1' where id=$1",
          [applicant],
        ),
      /permission denied|row-level security/,
    );
  });

  await check('legacy approved application activates as verified', async () => {
    await db.query(
      `insert into city_tenant_registrations(
        user_id,city,office_name,contact_person,contact_number,email,
        office_address,status,reviewed_by,reviewed_at
      ) values($1,'Meycauayan','Meycauayan Tourism Office','Legacy Applicant',
        '09170000002','legacy-office@example.test','City Hall','approved',$2,now())`,
      [legacyApplicant, mainTenant],
    );
    const result = await asUser(
      legacyApplicant,
      'select public.activate_approved_city_admin() as result',
      [],
      true,
    );
    assert.equal(result.rows[0].result.status, 'approved');
    assert.equal(
      (await db.query('select role from profiles where id=$1', [legacyApplicant]))
        .rows[0].role,
      'subtenant',
    );
    assert.equal(
      (
        await db.query(
          'select verification_status from subtenant_details where id=$1',
          [legacyApplicant],
        )
      ).rows[0].verification_status,
      'verified',
    );
  });

  await check('duplicate approved submission remains idempotent', async () => {
    const result = await asUser(applicant, submitSql, submitParams());
    assert.equal(result.rows[0].result.status, 'approved');
    assert.equal(
      (
        await db.query(
          'select count(*)::integer as count from city_tenant_registrations where user_id=$1',
          [applicant],
        )
      ).rows[0].count,
      1,
    );
  });

  await check('tourist privacy notice remains required and immutable', async () => {
    const anotherTourist = uuid(4);
    await db.query('insert into auth.users(id,email) values($1,$2)', [
      anotherTourist,
      'tourist2@example.test',
    ]);
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [
      anotherTourist,
    ]);
    await assert.rejects(
      () =>
        db.query("insert into profiles(id,role) values($1,'tourist')", [
          anotherTourist,
        ]),
      /PRIVACY_NOTICE_REQUIRED/,
    );
    await db.query(
      "insert into profiles(id,role,privacy_notice_version) values($1,'tourist','1.0')",
      [anotherTourist],
    );
    await assert.rejects(
      () =>
        db.query(
          "update profiles set privacy_notice_version='1.1' where id=$1",
          [anotherTourist],
        ),
      /PRIVACY_ACKNOWLEDGMENT_IMMUTABLE/,
    );
  });

  await check('forward migration is safely reapplicable', async () => {
    await db.exec(forwardMigration);
    assert.equal(
      (
        await db.query(
          "select count(*)::integer as count from profiles where id=$1 and role='subtenant'",
          [applicant],
        )
      ).rows[0].count,
      1,
    );
  });

  console.log(
    `PASS: ${checks} City Admin application/privacy database regression checks`,
  );
} finally {
  await db.close();
}
